/// `mont_mul` on aarch64: the portable version's no-final-carry CIOS, a row at a time with
/// one adds/adcs chain per row, closed by a branch-free subs/sbcs and csel. LLVM's code for
/// the portable version spends a cinc or cset per limb on carries and rematerialises the
/// modulus inside the loop.
#[inline(always)]
pub(super) fn mont_mul(a: [u64; 4], b: [u64; 4], m: &[u64; 4], n0: u64) -> [u64; 4] {
    let (t0, t1, t2, t3): (u64, u64, u64, u64);
    // SAFETY: register arithmetic only: no memory, no stack; flags clobbered.
    unsafe {
        core::arch::asm!(
            "mul {t0}, {a0}, {b0}",
            "mul {t1}, {a1}, {b0}",
            "mul {t2}, {a2}, {b0}",
            "mul {t3}, {a3}, {b0}",
            "umulh {tmp}, {a0}, {b0}",
            "adds {t1}, {t1}, {tmp}",
            "umulh {tmp}, {a1}, {b0}",
            "adcs {t2}, {t2}, {tmp}",
            "umulh {tmp}, {a2}, {b0}",
            "adcs {t3}, {t3}, {tmp}",
            "umulh {tmp}, {a3}, {b0}",
            "adc {t4}, {tmp}, xzr",
            "mul {m}, {t0}, {inv}",
            "mul {tmp}, {q0}, {m}",
            "adds {t0}, {t0}, {tmp}",
            "mul {tmp}, {q1}, {m}",
            "adcs {t1}, {t1}, {tmp}",
            "mul {tmp}, {q2}, {m}",
            "adcs {t2}, {t2}, {tmp}",
            "mul {tmp}, {q3}, {m}",
            "adcs {t3}, {t3}, {tmp}",
            "adc {t4}, {t4}, xzr",
            "umulh {tmp}, {q0}, {m}",
            "adds {t0}, {t1}, {tmp}",
            "umulh {tmp}, {q1}, {m}",
            "adcs {t1}, {t2}, {tmp}",
            "umulh {tmp}, {q2}, {m}",
            "adcs {t2}, {t3}, {tmp}",
            "umulh {tmp}, {q3}, {m}",
            "adc {t3}, {t4}, {tmp}",
            "mul {tmp}, {a0}, {b1}",
            "adds {t0}, {t0}, {tmp}",
            "mul {m}, {t0}, {inv}",
            "mul {tmp}, {a1}, {b1}",
            "adcs {t1}, {t1}, {tmp}",
            "mul {tmp}, {a2}, {b1}",
            "adcs {t2}, {t2}, {tmp}",
            "mul {tmp}, {a3}, {b1}",
            "adcs {t3}, {t3}, {tmp}",
            "adc {t4}, xzr, xzr",
            "umulh {tmp}, {a0}, {b1}",
            "adds {t1}, {t1}, {tmp}",
            "umulh {tmp}, {a1}, {b1}",
            "adcs {t2}, {t2}, {tmp}",
            "umulh {tmp}, {a2}, {b1}",
            "adcs {t3}, {t3}, {tmp}",
            "umulh {tmp}, {a3}, {b1}",
            "adc {t4}, {t4}, {tmp}",
            "mul {tmp}, {q0}, {m}",
            "adds {t0}, {t0}, {tmp}",
            "mul {tmp}, {q1}, {m}",
            "adcs {t1}, {t1}, {tmp}",
            "mul {tmp}, {q2}, {m}",
            "adcs {t2}, {t2}, {tmp}",
            "mul {tmp}, {q3}, {m}",
            "adcs {t3}, {t3}, {tmp}",
            "adc {t4}, {t4}, xzr",
            "umulh {tmp}, {q0}, {m}",
            "adds {t0}, {t1}, {tmp}",
            "umulh {tmp}, {q1}, {m}",
            "adcs {t1}, {t2}, {tmp}",
            "umulh {tmp}, {q2}, {m}",
            "adcs {t2}, {t3}, {tmp}",
            "umulh {tmp}, {q3}, {m}",
            "adc {t3}, {t4}, {tmp}",
            "mul {tmp}, {a0}, {b2}",
            "adds {t0}, {t0}, {tmp}",
            "mul {m}, {t0}, {inv}",
            "mul {tmp}, {a1}, {b2}",
            "adcs {t1}, {t1}, {tmp}",
            "mul {tmp}, {a2}, {b2}",
            "adcs {t2}, {t2}, {tmp}",
            "mul {tmp}, {a3}, {b2}",
            "adcs {t3}, {t3}, {tmp}",
            "adc {t4}, xzr, xzr",
            "umulh {tmp}, {a0}, {b2}",
            "adds {t1}, {t1}, {tmp}",
            "umulh {tmp}, {a1}, {b2}",
            "adcs {t2}, {t2}, {tmp}",
            "umulh {tmp}, {a2}, {b2}",
            "adcs {t3}, {t3}, {tmp}",
            "umulh {tmp}, {a3}, {b2}",
            "adc {t4}, {t4}, {tmp}",
            "mul {tmp}, {q0}, {m}",
            "adds {t0}, {t0}, {tmp}",
            "mul {tmp}, {q1}, {m}",
            "adcs {t1}, {t1}, {tmp}",
            "mul {tmp}, {q2}, {m}",
            "adcs {t2}, {t2}, {tmp}",
            "mul {tmp}, {q3}, {m}",
            "adcs {t3}, {t3}, {tmp}",
            "adc {t4}, {t4}, xzr",
            "umulh {tmp}, {q0}, {m}",
            "adds {t0}, {t1}, {tmp}",
            "umulh {tmp}, {q1}, {m}",
            "adcs {t1}, {t2}, {tmp}",
            "umulh {tmp}, {q2}, {m}",
            "adcs {t2}, {t3}, {tmp}",
            "umulh {tmp}, {q3}, {m}",
            "adc {t3}, {t4}, {tmp}",
            "mul {tmp}, {a0}, {b3}",
            "adds {t0}, {t0}, {tmp}",
            "mul {m}, {t0}, {inv}",
            "mul {tmp}, {a1}, {b3}",
            "adcs {t1}, {t1}, {tmp}",
            "mul {tmp}, {a2}, {b3}",
            "adcs {t2}, {t2}, {tmp}",
            "mul {tmp}, {a3}, {b3}",
            "adcs {t3}, {t3}, {tmp}",
            "adc {t4}, xzr, xzr",
            "umulh {tmp}, {a0}, {b3}",
            "adds {t1}, {t1}, {tmp}",
            "umulh {tmp}, {a1}, {b3}",
            "adcs {t2}, {t2}, {tmp}",
            "umulh {tmp}, {a2}, {b3}",
            "adcs {t3}, {t3}, {tmp}",
            "umulh {tmp}, {a3}, {b3}",
            "adc {t4}, {t4}, {tmp}",
            "mul {tmp}, {q0}, {m}",
            "adds {t0}, {t0}, {tmp}",
            "mul {tmp}, {q1}, {m}",
            "adcs {t1}, {t1}, {tmp}",
            "mul {tmp}, {q2}, {m}",
            "adcs {t2}, {t2}, {tmp}",
            "mul {tmp}, {q3}, {m}",
            "adcs {t3}, {t3}, {tmp}",
            "adc {t4}, {t4}, xzr",
            "umulh {tmp}, {q0}, {m}",
            "adds {t0}, {t1}, {tmp}",
            "umulh {tmp}, {q1}, {m}",
            "adcs {t1}, {t2}, {tmp}",
            "umulh {tmp}, {q2}, {m}",
            "adcs {t2}, {t3}, {tmp}",
            "umulh {tmp}, {q3}, {m}",
            "adc {t3}, {t4}, {tmp}",
            "subs {a0}, {t0}, {q0}",
            "sbcs {a1}, {t1}, {q1}",
            "sbcs {a2}, {t2}, {q2}",
            "sbcs {a3}, {t3}, {q3}",
            "csel {t0}, {a0}, {t0}, cs",
            "csel {t1}, {a1}, {t1}, cs",
            "csel {t2}, {a2}, {t2}, cs",
            "csel {t3}, {a3}, {t3}, cs",
            a0 = inout(reg) a[0] => _,
            a1 = inout(reg) a[1] => _,
            a2 = inout(reg) a[2] => _,
            a3 = inout(reg) a[3] => _,
            b0 = in(reg) b[0],
            b1 = in(reg) b[1],
            b2 = in(reg) b[2],
            b3 = in(reg) b[3],
            q0 = in(reg) m[0],
            q1 = in(reg) m[1],
            q2 = in(reg) m[2],
            q3 = in(reg) m[3],
            inv = in(reg) n0,
            t0 = out(reg) t0,
            t1 = out(reg) t1,
            t2 = out(reg) t2,
            t3 = out(reg) t3,
            t4 = out(reg) _,
            m = out(reg) _,
            tmp = out(reg) _,
            options(pure, nomem, nostack),
        );
    }
    [t0, t1, t2, t3]
}
