#!/usr/bin/env bash
# Point every arkworks 0.5 crate in the graph at one local checkout of arkworks-rs/algebra,
# for an A/B of two arkworks builds from the same snarkrs commit.
#
#   bench/scripts/ark-patch.sh ALGEBRA_DIR   add or replace the [patch.crates-io] block
#   bench/scripts/ark-patch.sh --remove      take it out again
#
# All of ark-ff, ark-ff-macros, ark-ff-asm, ark-ec, ark-poly, ark-serialize and
# ark-serialize-derive are patched, never a subset: patching some leaves a second copy of the
# rest in the graph and the traits stop matching. ark-std lives in its own repository and
# stays on crates.io. So does ark-bn254: at the v0.5.0 tag curves/ is still versioned
# 0.5.0-alpha.0, which cargo will not substitute for 0.5, and its src is byte-identical to
# the crates.io 0.5.0 one. Its Fq and Fr code is generated by the patched ark-ff-macros, so
# the patch still reaches it. The block changes Cargo.lock; commit neither.
set -euo pipefail

repo=$(cd "$(dirname "$0")/../.." && pwd)
manifest=$repo/Cargo.toml
begin="# BEGIN ark-patch.sh (do not commit)"
end="# END ark-patch.sh"

strip() {
  awk -v b="$begin" -v e="$end" '$0 == b {skip = 1} !skip {print} $0 == e {skip = 0}' "$manifest" > "$manifest.tmp"
  # The block is appended after one blank line; drop that line with it.
  sed -e :a -e '/^\n*$/{$d;N;ba' -e '}' "$manifest.tmp" > "$manifest"
  rm "$manifest.tmp"
}

case ${1:-} in
  --remove)
    strip
    ;;
  "" | -h | --help)
    sed -n '2,14p' "$0"
    exit 2
    ;;
  *)
    dir=$(cd "$1" && pwd)
    for d in ff ff-macros ff-asm ec poly serialize serialize-derive; do
      [[ -f $dir/$d/Cargo.toml ]] || { echo "no $d/Cargo.toml under $dir" >&2; exit 1; }
    done
    strip
    {
      echo
      echo "$begin"
      echo "[patch.crates-io]"
      for p in "ark-ff ff" "ark-ff-macros ff-macros" "ark-ff-asm ff-asm" "ark-ec ec" "ark-poly poly" \
        "ark-serialize serialize" "ark-serialize-derive serialize-derive"; do
        set -- $p
        echo "$1 = { path = \"$dir/$2\" }"
      done
      echo "$end"
    } >> "$manifest"
    ;;
esac
