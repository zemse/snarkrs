import * as binFileUtils from "@iden3/binfileutils";
import { buildBn128, Scalar } from "ffjavascript";
import fs from "fs";
const dir=process.argv[2], outp=process.argv[3];
const curve = await buildBn128(); const Fr=curve.Fr, G1=curve.G1, G2=curve.G2;
const {fd:fz, sections:sz} = await binFileUtils.readBinFile(dir+"/circuit.zkey","zkey",2,1<<25,1<<23);
const {fd:fw, sections:sw} = await binFileUtils.readBinFile(dir+"/circuit.wtns","wtns",2,1<<25,1<<23);
const s2 = await binFileUtils.readSection(fz,sz,2);
const dv=new DataView(s2.buffer,s2.byteOffset);
let o=0; const n8q=dv.getUint32(0,true); o=4+n8q; const n8r=dv.getUint32(o,true); o+=4+n8r;
const nVars=dv.getUint32(o,true), nPublic=dv.getUint32(o+4,true), domainSize=dv.getUint32(o+8,true);
const power=Math.round(Math.log2(domainSize));
const W = await binFileUtils.readSection(fw,sw,2);
const C = await binFileUtils.readSection(fz,sz,4);
const n8=Fr.n8, sCoef=12+n8r, nCoef=(C.byteLength-4)/sCoef;
const A=new Uint8Array(domainSize*n8), B=new Uint8Array(domainSize*n8), Cc=new Uint8Array(domainSize*n8);
const ob=[A,B];
for(let i=0;i<nCoef;i++){const bc=C.slice(4+i*sCoef,4+i*sCoef+sCoef);const v=new DataView(bc.buffer,bc.byteOffset);
 const m=v.getUint32(0,true),c=v.getUint32(4,true),s=v.getUint32(8,true);const coef=bc.slice(12,12+n8);
 ob[m].set(Fr.add(ob[m].slice(c*n8,c*n8+n8),Fr.mul(coef,W.slice(s*n8,s*n8+n8))),c*n8);}
for(let i=0;i<domainSize;i++) Cc.set(Fr.mul(A.slice(i*n8,i*n8+n8),B.slice(i*n8,i*n8+n8)),i*n8);
const inc = power==Fr.s?Fr.shift:Fr.w[power+1];
const tr=async b=>{let x=await Fr.ifft(b);x=await Fr.batchApplyKey(x,Fr.e(1),inc);return await Fr.fft(x);};
const At=await tr(A),Bt=await tr(B),Ct=await tr(Cc);
const P=new Uint8Array(domainSize*n8);
for(let i=0;i<domainSize;i++) P.set(Fr.sub(Fr.mul(At.slice(i*n8,i*n8+n8),Bt.slice(i*n8,i*n8+n8)),Ct.slice(i*n8,i*n8+n8)),i*n8);
// joinABC leaves normal form for multiexp
const Pn=new Uint8Array(domainSize*n8);
for(let i=0;i<domainSize;i++) Pn.set(Fr.fromMontgomery(P.slice(i*n8,i*n8+n8)),i*n8);
const b5=await binFileUtils.readSection(fz,sz,5);
const b6=await binFileUtils.readSection(fz,sz,6);
const b7=await binFileUtils.readSection(fz,sz,7);
const b8=await binFileUtils.readSection(fz,sz,8);
const b9=await binFileUtils.readSection(fz,sz,9);
const a_g1=await G1.multiExpAffine(b5,W);
const b_g1=await G1.multiExpAffine(b6,W);
const b_g2=await G2.multiExpAffine(b7,W);
const l_g1=await G1.multiExpAffine(b8,W.slice((nPublic+1)*n8));
const h_g1=await G1.multiExpAffine(b9,Pn);
const j1=p=>G1.toObject(G1.toAffine(p)).map(x=>x.toString());
const j2=p=>G2.toObject(G2.toAffine(p)).map(c=>c.map(x=>x.toString()));
fs.writeFileSync(outp, JSON.stringify({nVars,nPublic,domainSize,a_g1:j1(a_g1),b_g1:j1(b_g1),b_g2:j2(b_g2),l_g1:j1(l_g1),h_g1:j1(h_g1)},null,1));
console.log("wrote",outp,"a_g1[0]",j1(a_g1)[0].slice(0,20),"l_g1[0]",j1(l_g1)[0].slice(0,20));
await fz.close(); await fw.close(); await curve.terminate();
